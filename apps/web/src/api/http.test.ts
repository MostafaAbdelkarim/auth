import { http as mock, HttpResponse } from 'msw';
import { fail, ok, SERVER_CORRELATION_ID } from '../test/handlers';
import { server } from '../test/server';
import { ApiError, buildUrl, http, onSessionExpired, request } from './http';

describe('buildUrl', () => {
  it('prefixes /api, fills and encodes path params and builds the query string', () => {
    expect(
      buildUrl(
        '/users/:id/posts',
        { id: 'a/b c' },
        { page: 2, q: 'x&y', empty: undefined, none: null },
      ),
    ).toBe(`${window.location.origin}/api/users/a%2Fb%20c/posts?page=2&q=x%26y`);
  });

  it('fails loudly when a path param is missing', () => {
    expect(() => buildUrl('/users/:id')).toThrow('Missing path parameter "id"');
  });
});

describe('correlation ids (generated by the API only)', () => {
  const HEADER_ID = '3b241101-e2bb-4255-8caf-4136c566a962';

  it('never sends X-Correlation-Id, not even on the session refresh or the retry', async () => {
    const sent: Array<string | null> = [];
    let calls = 0;
    server.use(
      mock.get('*/api/users/me', ({ request: req }) => {
        sent.push(req.headers.get('x-correlation-id'));
        calls += 1;
        return calls === 1 ? fail(401, 'INVALID_ACCESS_TOKEN') : ok({ id: 'u1' });
      }),
      mock.post('*/api/auth/refresh', ({ request: req }) => {
        sent.push(req.headers.get('x-correlation-id'));
        return ok(null);
      }),
    );

    await http.get('/users/me');
    expect(sent).toEqual([null, null, null]);
  });

  it("takes the reference from the response header when the error body doesn't carry one", async () => {
    server.use(
      mock.get('*/api/things', () =>
        HttpResponse.json(
          {
            success: false,
            error: { statusCode: 500, code: 'INTERNAL_ERROR', message: 'x' },
            meta: { correlationId: '' },
          },
          { status: 500, headers: { 'X-Correlation-Id': HEADER_ID } },
        ),
      ),
    );
    const error = (await http.get('/things').catch((e: unknown) => e)) as ApiError;
    expect(error.correlationId).toBe(HEADER_ID);
  });

  it('takes the reference from the response header for a non-envelope response', async () => {
    server.use(
      mock.get('*/api/things', () =>
        HttpResponse.json(
          { not: 'an envelope' },
          { status: 500, headers: { 'X-Correlation-Id': HEADER_ID } },
        ),
      ),
    );
    const error = (await http.get('/things').catch((e: unknown) => e)) as ApiError;
    expect(error.correlationId).toBe(HEADER_ID);
  });

  it('has no reference when the API never handled the request', async () => {
    server.use(mock.get('*/api/down', () => HttpResponse.error()));
    server.use(
      mock.get('*/api/proxy', () => new HttpResponse('<html>502</html>', { status: 502 })),
    );

    const offline = (await http.get('/down').catch((e: unknown) => e)) as ApiError;
    const proxyError = (await http.get('/proxy').catch((e: unknown) => e)) as ApiError;
    expect(offline.correlationId).toBeUndefined();
    expect(proxyError.correlationId).toBeUndefined();
  });
});

describe('request', () => {
  it('unwraps the success envelope', async () => {
    server.use(mock.get('*/api/things', () => ok({ id: 1 })));
    await expect(request({ path: '/things' })).resolves.toEqual({ id: 1 });
  });

  it('sends JSON bodies and cookies with every method helper', async () => {
    const seen: Array<[string, unknown, string | null]> = [];
    const record = async ({ request: req }: { request: Request }) => {
      const text = await req.text();
      seen.push([req.method, text ? JSON.parse(text) : undefined, req.headers.get('content-type')]);
      return ok(null);
    };
    server.use(
      mock.get('*/api/r', record),
      mock.post('*/api/r', record),
      mock.put('*/api/r', record),
      mock.patch('*/api/r', record),
      mock.delete('*/api/r', record),
    );

    await http.get('/r');
    await http.post('/r', { a: 1 });
    await http.put('/r', { b: 2 });
    await http.patch('/r', { c: 3 });
    await http.delete('/r');
    await http.post('/r');

    expect(seen).toEqual([
      ['GET', undefined, null],
      ['POST', { a: 1 }, 'application/json'],
      ['PUT', { b: 2 }, 'application/json'],
      ['PATCH', { c: 3 }, 'application/json'],
      ['DELETE', undefined, null],
      ['POST', undefined, null],
    ]);
  });

  it('turns the error envelope into an ApiError with code, details and request id', async () => {
    server.use(
      mock.post('*/api/auth/signup', () =>
        fail(400, 'VALIDATION_FAILED', 'Request validation failed', ['a', 'b']),
      ),
    );
    const error = (await http.post('/auth/signup', {}).catch((e: unknown) => e)) as ApiError;
    expect(error).toBeInstanceOf(ApiError);
    expect(error).toMatchObject({
      status: 400,
      code: 'VALIDATION_FAILED',
      message: 'Request validation failed',
      details: ['a', 'b'],
      correlationId: SERVER_CORRELATION_ID,
    });
  });

  it('reports a response without an envelope (e.g. a proxy error page)', async () => {
    server.use(
      mock.get('*/api/things', () => new HttpResponse('<html>502</html>', { status: 502 })),
    );
    await expect(request({ path: '/things' })).rejects.toMatchObject({
      status: 502,
      code: 'UNEXPECTED_RESPONSE',
    });
  });

  it('reports JSON that is not an envelope as unexpected', async () => {
    server.use(mock.get('*/api/things', () => HttpResponse.json({ hello: 'world' })));
    await expect(request({ path: '/things' })).rejects.toMatchObject({
      code: 'UNEXPECTED_RESPONSE',
    });
  });

  it('reports a network failure', async () => {
    server.use(mock.get('*/api/things', () => HttpResponse.error()));
    await expect(request({ path: '/things' })).rejects.toMatchObject({
      status: 0,
      code: 'NETWORK_ERROR',
    });
  });

  it('lets an aborted request reject with the abort error', async () => {
    server.use(mock.get('*/api/slow', () => new Promise(() => undefined)));
    const controller = new AbortController();
    const pending = request({ path: '/slow', signal: controller.signal });
    controller.abort();
    await expect(pending).rejects.toMatchObject({ name: 'AbortError' });
  });

  describe('session refresh', () => {
    it('refreshes once on 401 and retries the request', async () => {
      let calls = 0;
      let refreshes = 0;
      server.use(
        mock.get('*/api/users/me', () => {
          calls += 1;
          return calls === 1 ? fail(401, 'INVALID_ACCESS_TOKEN') : ok({ id: 'u1' });
        }),
        mock.post('*/api/auth/refresh', () => {
          refreshes += 1;
          return ok(null);
        }),
      );

      await expect(http.get('/users/me')).resolves.toEqual({ id: 'u1' });
      expect([calls, refreshes]).toEqual([2, 1]);
    });

    it('shares one refresh between concurrent 401s', async () => {
      let refreshes = 0;
      let authorised = false;
      server.use(
        mock.get('*/api/users/me', () =>
          authorised ? ok({ id: 'u1' }) : fail(401, 'INVALID_ACCESS_TOKEN'),
        ),
        mock.post('*/api/auth/refresh', () => {
          refreshes += 1;
          authorised = true;
          return ok(null);
        }),
      );

      await Promise.all([http.get('/users/me'), http.get('/users/me')]);
      expect(refreshes).toBe(1);
    });

    it('gives up with the original 401 when refresh fails', async () => {
      server.use(
        mock.get('*/api/users/me', () => fail(401, 'AUTHENTICATION_REQUIRED')),
        mock.post('*/api/auth/refresh', () => fail(401, 'INVALID_REFRESH_TOKEN')),
      );
      await expect(http.get('/users/me')).rejects.toMatchObject({
        status: 401,
        code: 'AUTHENTICATION_REQUIRED',
      });
    });

    it('treats a refresh network failure as a failed refresh', async () => {
      server.use(
        mock.get('*/api/users/me', () => fail(401, 'AUTHENTICATION_REQUIRED')),
        mock.post('*/api/auth/refresh', () => HttpResponse.error()),
      );
      await expect(http.get('/users/me')).rejects.toMatchObject({ status: 401 });
    });

    it('announces an expired session when the server rejects the refresh', async () => {
      server.use(
        mock.get('*/api/things', () => fail(401, 'INVALID_ACCESS_TOKEN')),
        mock.post('*/api/auth/refresh', () => fail(401, 'INVALID_REFRESH_TOKEN')),
      );
      const listener = vi.fn();
      const unsubscribe = onSessionExpired(listener);

      await expect(http.get('/things')).rejects.toMatchObject({ status: 401 });
      expect(listener).toHaveBeenCalledTimes(1);

      unsubscribe();
      await expect(http.get('/things')).rejects.toMatchObject({ status: 401 });
      expect(listener).toHaveBeenCalledTimes(1);
    });

    it('does not announce an expired session when the refresh could not reach the server', async () => {
      server.use(
        mock.get('*/api/things', () => fail(401, 'INVALID_ACCESS_TOKEN')),
        mock.post('*/api/auth/refresh', () => HttpResponse.error()),
      );
      const listener = vi.fn();
      const unsubscribe = onSessionExpired(listener);

      await expect(http.get('/things')).rejects.toMatchObject({ status: 401 });
      expect(listener).not.toHaveBeenCalled();
      unsubscribe();
    });

    it('does not announce an expired session for calls that opt out of refresh', async () => {
      server.use(mock.post('*/api/auth/signin', () => fail(401, 'INVALID_CREDENTIALS')));
      const listener = vi.fn();
      const unsubscribe = onSessionExpired(listener);

      await expect(
        http.post('/auth/signin', {}, { retryOnUnauthorized: false }),
      ).rejects.toMatchObject({ code: 'INVALID_CREDENTIALS' });
      expect(listener).not.toHaveBeenCalled();
      unsubscribe();
    });

    it('does not refresh when the call opts out', async () => {
      let refreshes = 0;
      server.use(
        mock.post('*/api/auth/signin', () => fail(401, 'INVALID_CREDENTIALS')),
        mock.post('*/api/auth/refresh', () => {
          refreshes += 1;
          return ok(null);
        }),
      );
      await expect(
        http.post('/auth/signin', {}, { retryOnUnauthorized: false }),
      ).rejects.toMatchObject({ code: 'INVALID_CREDENTIALS' });
      expect(refreshes).toBe(0);
    });
  });
});
